			  <p id="p2">RULES</p>
	<style="font face="Montserrat"><b>There will be two levels:</b></style>
	<p class= " pad"><b>Level 1:</b>
All the teams by default will enter in level one. The difficulty level for this round will be intermediate. 
For each round, 4 teams will play at a time and winner of each round will go to level 2.<br/>
                <b>Level 2:</b>
All winnesr of level 1 will play in this level. This level will consist of one round only. Difficulty level for this round will be hard. The winner will be selected on the basis of the points earned. The board will be divided into four parts:
Fun lane
Initially four team will start from starting point. First team will be given a die to roll. According to die the task will be assigned to the team. All the team members have to actively participate in the task. Similarly, other teams will be given a task based on the number on the die. Each fun task will be of 10 mins.
Mechanical Lane
After first round all teams will be on “Mech Point”. In mechanical lane all the task will be related to mechanics. Similarly to fun lane, participants has to roll die and has to perform the task accordingly. All these task will be done in a different room. Each task will be of 30 mins.
Coding Lane
After the Mechanical lane the participants will be on “Code point”. In Coding lane all the task will be related to coding. The coding will be in either in “C or Java”. Task will be given on die roll. All these task will be done in computer lab. This round will be of 30 mins.
Electronic Lane
After Coding lane the participants will reach “Silicon valley”. In Electronics lane all the task will be related to electronics. Task will be given on die roll. All these task will be done in a room. Each task will be of 30 mins.
