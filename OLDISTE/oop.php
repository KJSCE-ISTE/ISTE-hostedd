				<font color="#459588"><b>Description :</b></font>
						<p class="pad"><ul><li>The first ISTE event of the even semester was a seminar on the basic concepts of object-oriented programming using Java programming language. This seminar was primarily for First Year Engineering students but was open to anyone wishing to revise their OOP basics.</li>
						<li>The seminar began with a general overview of programming, wherein variables and data types were explained, and later covered the 3 major OOP concepts of Encapsulation, Inheritance and Polymorphism. A number of Java example programs were shown in the presentation in order to clarify these concepts, and at the same time familiarize the students with the syntax of Java. At the end of the presentation, an application game of X and Zero was demonstrated to them using Eclipse software.</li></ul><br/>
						</p>

