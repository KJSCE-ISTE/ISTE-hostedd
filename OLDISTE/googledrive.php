				<font color="#459588"><b>Description :</b></font>
						<p class="pad">The Workshop started up with the Overview of "Google Drive", it's major functionalities including the Collaborative Editing and the optimization of the same. The concept of <b>Cloud Storage</b> was very well explained to the Students with it's existence, applications and real-time examples.
As Sharing the Files, Creating/Editing the documents online, all the Documentation work of ones' Multi-Purposed projects whether it be <i>.ppt or .docx</i>, etc. All these activities are carried out by each Engineer irrespective of their branches, the point of branch independency was clearly proved. One need not have paid versions of <b>Microsoft Office</b> on <b>Windows</b> or <b>Libre Office</b> on <b>Ubuntu</b>. All that's required is the Internet Access, and all your files can be created online without any pre-installation of such bulky softwares. The sole motto of the Workshop was to make people aware of this awesome Google Service and explain them some interesting features of Collaborative Editing which helps creating a virtual environment of working together.</p>

